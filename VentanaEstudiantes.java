    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
        // TODO add your handling code here:
        
String nombre = txtNombre.getText().trim();
String rut = txtRut.getText().trim();
String curso = txtCurso.getText().trim();
String correo = txtCorreo.getText().trim();

if (nombre.isEmpty() || rut.isEmpty()
        || curso.isEmpty() || correo.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Complete todos los campos"
    );
    return;
}

try (java.sql.Connection con =
        conexion.ConexionBiblioteca.getConexion()) {

    String sql = "INSERT INTO estudiantes "
            + "(nombre, rut, curso, correo) VALUES (?, ?, ?, ?)";

    try (java.sql.PreparedStatement ps = con.prepareStatement(sql)) {
        ps.setString(1, nombre);
        ps.setString(2, rut);
        ps.setString(3, curso);
        ps.setString(4, correo);

        ps.executeUpdate();

        javax.swing.JOptionPane.showMessageDialog(
            this, "Estudiante registrado correctamente"
        );

        txtNombre.setText("");
        txtRut.setText("");
        txtCurso.setText("");
        txtCorreo.setText("");
    }

} catch (java.sql.SQLException e) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Error al registrar estudiante: " + e.getMessage()
    );
}

    }//GEN-LAST:event_btnRegistrarActionPerformed

    private void btnListarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnListarActionPerformed
        // TODO add your handling code here:
        
javax.swing.table.DefaultTableModel modeloTabla =
    new javax.swing.table.DefaultTableModel();

modeloTabla.addColumn("ID");
modeloTabla.addColumn("Nombre");
modeloTabla.addColumn("RUT");
modeloTabla.addColumn("Curso");
modeloTabla.addColumn("Correo");

String sql = "SELECT id, nombre, rut, curso, correo FROM estudiantes";

try (java.sql.Connection con =
        conexion.ConexionBiblioteca.getConexion();
     java.sql.PreparedStatement ps = con.prepareStatement(sql);
     java.sql.ResultSet rs = ps.executeQuery()) {

    while (rs.next()) {
        modeloTabla.addRow(new Object[] {
            rs.getInt("id"),
            rs.getString("nombre"),
            rs.getString("rut"),
            rs.getString("curso"),
            rs.getString("correo")
        });
    }

    tablaEstudiantes.setModel(modeloTabla);

} catch (java.sql.SQLException e) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Error al listar estudiantes: " + e.getMessage()
    );
}

    }//GEN-LAST:event_btnListarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        // TODO add your handling code here:
        
int fila = tablaEstudiantes.getSelectedRow();

if (fila == -1) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Seleccione un estudiante de la tabla"
    );
    return;
}

int id = Integer.parseInt(
    tablaEstudiantes.getValueAt(fila, 0).toString()
);

int confirmar = javax.swing.JOptionPane.showConfirmDialog(
    this,
    "Desea eliminar este estudiante?",
    "Confirmar eliminacion",
    javax.swing.JOptionPane.YES_NO_OPTION
);

if (confirmar != javax.swing.JOptionPane.YES_OPTION) {
    return;
}

String sql = "DELETE FROM estudiantes WHERE id = ?";

try (java.sql.Connection con =
        conexion.ConexionBiblioteca.getConexion();
     java.sql.PreparedStatement ps = con.prepareStatement(sql)) {

    ps.setInt(1, id);

    if (ps.executeUpdate() > 0) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Estudiante eliminado correctamente"
        );

        btnListar.doClick();
    } else {
        javax.swing.JOptionPane.showMessageDialog(
            this, "No se encontro el estudiante"
        );
    }

} catch (java.sql.SQLException e) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Error al eliminar estudiante: " + e.getMessage()
    );
}

    }//GEN-LAST:event_btnEliminarActionPerformed

