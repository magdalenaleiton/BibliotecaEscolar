    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
        // TODO add your handling code here:
String nombre = txtNombre.getText().trim();

if (nombre.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Ingrese el nombre de la categoria"
    );
    return;
}

modelo.Categoria categoria = new modelo.Categoria();
categoria.setNombre(nombre);

dao.CategoriaDAO daoCategoria = new dao.CategoriaDAO();

if (daoCategoria.insertar(categoria)) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Categoria registrada correctamente"
    );
    txtNombre.setText("");
} else {
    javax.swing.JOptionPane.showMessageDialog(
        this, "No se pudo registrar la categoria"
    );
}


    }//GEN-LAST:event_btnRegistrarActionPerformed

